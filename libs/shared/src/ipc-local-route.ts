import type { MachineChannel } from './ipc-scope'

/**
 * How Desktop main serves each machine channel once This Mac's lanes belong to
 * the local Phosphor service (daemon mode). App channels are not listed: they
 * are Desktop's own device services by definition (`IPC_SCOPE`). In-app mode
 * ignores this table. See docs/remote-desktop.md.
 *
 * - `host`: the handler reaches every machine through the Host protocol (it
 *   takes a Host id, a target or a lane handle); unchanged in both modes.
 * - `same-machine`: Desktop main touches This Mac's files or OS directly. A
 *   `host:<this Mac>/lane:<id>` or `/repo:<id>` key resolves to its real path
 *   from the local connection's projection, then the unchanged handler runs.
 * - `leased`: same-machine, and the handler reserves the folder with an owner
 *   lease instead of consulting the in-app session registry.
 * - `app`: a Desktop service (dialogs, staging, sign-in drivers) that never
 *   touches lane state; unchanged in both modes.
 * - `in-app-only`: the handler reads or writes the in-app runtime's own state
 *   (pi sessions, pi config, routines, accounts, terminals). It fails closed in
 *   daemon mode; the remote router still serves `host:` keys before it.
 */
export type LocalRoute = 'host' | 'same-machine' | 'leased' | 'app' | 'in-app-only'

