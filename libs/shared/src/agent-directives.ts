import type { AgentDirectivePrefs, GitInfo } from './models'
import { machinePromptBlock, type MachineContext } from './machine-prompt'

/** Shared by the session prompt and Settings preview: one tool-scoped policy. */
export function subagentPolicyBlock(): string {
  return [
    '<phosphor_subagents>',
    'When sub-agent tools are available, use them only for genuinely broad, independent work.',
    '- Native Claude Code Agent/Task: prefer run_in_background: false when its schema supports it; wait for the findings.',
    '- pi subagent: follow its advertised schema. Do not add run_in_background; that parameter belongs to Agent.',
    '- Answer directly when you can. Reading a handful of files is not a fan-out.',
    '</phosphor_subagents>',
  ].join('\n')
}

/**
 * The `--append-system-prompt` block Phosphor adds for worktree sessions.
 *
 * pi already ends its system prompt with one `Current working directory: …`
 * line, and that line is correct. It is not enough: when the worktree sits
 * *inside* its own main checkout — which is exactly where Phosphor puts them,
 * `<repo>/.phosphor/worktrees/<name>` — the cwd string contains the main
 * checkout as a prefix, and a model absolutising a relative path has been
 * observed to trim the `.phosphor/worktrees/<name>` segment back off. The
 * shortened path exists and opens, so the mistake returns another branch's
 * code instead of an error (session 01a02ca0: one of two reads).
 *
 * So this says the part pi's line leaves implicit: the prefix is load-bearing
 * and the main checkout is a different branch. `libs/pi-extensions/pi-ext/worktree-paths.ts` is
 * the backstop that makes it loud when a model does it anyway.
 *
 * Nothing is appended for ordinary (non-worktree) sessions — pi's own line
 * already covers them, and every token here is spent on every request.
 */
export function worktreePromptBlock(cwd: string, git: GitInfo): string | undefined {
  if (!git.isRepo || !git.isWorktree || !git.mainRepoPath) return undefined
  if (git.mainRepoPath === cwd) return undefined

  return [
    '<phosphor_workspace>',
    `Working directory: ${cwd}`,
    `This session runs in a git worktree. The repository's main checkout is at ` +
      `${git.mainRepoPath} and is on a DIFFERENT branch.`,
    '- Resolve every relative path against the working directory above.',
    '- When a tool wants an absolute path, build it by prefixing the working directory',
    `  verbatim. Never shorten it to ${git.mainRepoPath} — files there belong to another`,
    '  branch, and reading them returns stale code with no error.',
    '</phosphor_workspace>',
  ].join('\n')
}

/**
 * The directive stack: everything Phosphor appends to a lane's system prompt.
 *
 * Four layers reach a lane and only two of them are ours:
 *
 *   1. The agent's own system prompt. Not ours, fixed at spawn, reloaded on
 *      compaction.
 *   2. **This.** The worktree warning, machine context, lane charter and
 *      sub-agent policy, concatenated in a fixed order and passed as
 *      `--append-system-prompt`. Generated, because they carry per-lane facts
 *      (worktree, branch, machine) and Phosphor maintains their wording.
 *   3. Rules files, loaded by pi into its assembled system prompt: the user's
 *      global `<agent dir>/AGENTS.md` (their own instructions, edited in
 *      Settings and kept current in running lanes by `pi-ext/global-context.ts`),
 *      then the repository's. The Claude context policy disables the CLI's
 *      independent copy. Like other prose instructions, these guide behavior
 *      rather than enforcing it.
 *   4. Our extensions, running inside the turn. Not prose: they refuse,
 *      rewrite and measure.
 *
 * Layer 2 used to be one hardcoded string. It has to be a setting now, because
 * the right contents depend on which model the lane is running: Anthropic cut
 * its frontier harness prompt from roughly 2,686 words to about 514 with
 * memory off (the widely quoted 80%) and about 830 with memory on (nearer
 * 70%), and the cut is frontier-only. A mixed fleet therefore needs two
 * prompt profiles — lean for models that are better without scaffolding, fuller
 * for everything else — and a single constant compiled into the app cannot
 * express that.
 *
 * Every block is individually toggleable and Settings previews this same
 * function's output before it is sent. Nothing here is generated by a model.
 */

export interface LaneCharter {
  /** Branch this lane owns, when it has one. */
  branch?: string
  /** Base the lane branched from, for the eventual PR. */
  base?: string
}

/**
 * What the lane is for, and how it ends.
 *
 * The pull request is stated in the first system prompt the lane ever sees,
 * not discovered at the end. An agent that learns late that its work needs a
 * PR has already made every decision that makes one hard: one enormous commit,
 * a branch that never rebased, a diff nobody sized.
 *
 * Kept deliberately short. This is a budget, not an essay, and every token
 * here is spent on every request for the life of the lane.
 */
export function laneCharterBlock(charter: LaneCharter): string {
  const lines = [
    '<phosphor_lane>',
    'This session is a LANE: one unit of work, on its own branch, that ends in a',
    'pull request. Not a scratch session.',
  ]
  if (charter.branch) {
    lines.push(`Branch: ${charter.branch}${charter.base ? ` (from ${charter.base})` : ''}`)
  }
  lines.push(
    '- Commit your work on this branch as you go. Do not commit to the base branch.',
    '- Open a pull request when the work is done. That is how this lane closes.',
    '- Keep the change reviewable: aim under 400 changed lines and 20 files. If the',
    '  work is genuinely larger, land it as a stack of smaller PRs rather than one.',
    "- Run the project's own typecheck, tests and lint before you claim the work is",
    '  done. Saying it is done is not evidence; an exit code is.',
    '</phosphor_lane>',
  )
  return lines.join('\n')
}

export interface ComposeDirectivesOptions {
  cwd: string
  git: GitInfo
  prefs: AgentDirectivePrefs
  machine?: MachineContext
  charter?: LaneCharter
}

/**
 * Compose layer 2, in a fixed order.
 *
 * Order is part of the contract: the worktree warning first because it is a
 * correctness guard, machine context next to locate the lane, then the charter
 * because it defines the work, and the sub-agent policy after it because it
 * constrains how the work is done. The user's own instructions are not here:
 * they live in the global AGENTS.md, which pi renders after this layer.
 */
export function composeDirectives({
  cwd,
  git,
  prefs,
  charter,
  machine,
}: ComposeDirectivesOptions): string | undefined {
  const blocks: (string | undefined)[] = [
    prefs.worktreeGuard ? worktreePromptBlock(cwd, git) : undefined,
    prefs.machineAwareness !== false ? machinePromptBlock(machine) : undefined,
    prefs.laneCharter && charter ? laneCharterBlock(charter) : undefined,
    prefs.subagentPolicy ? subagentPolicyBlock() : undefined,
  ]
  return blocks.filter(Boolean).join('\n\n') || undefined
}
